/**
 * The three doors into a forge, in one place: `/llms.txt` leads with them and
 * a repository without an AGENTS.md of its own is answered with them
 * (`/<owner>/<repo>/AGENTS.md`, `src/http/agents_md.ts`). Fixed words and the
 * origin and repository the caller already validated: nothing here echoes a
 * request.
 */

/** The one host a sandbox must allow to use every door: this forge's own. */
export const egressHost = (origin: string): string => new URL(origin).host;

/** llms.txt's opening: the doors, the commands, the egress host. */
export function threeDoors(origin: string, mcpUrl: string): string[] {
  return [
    `## Three doors`,
    "",
    `Egress: allow one host, ${egressHost(origin)} (this forge).`,
    "",
    `1. Git: \`git clone ${origin}/{owner}/{name}.git\`, \`git push origin <branch>\` with a token as password; a person merges.`,
    `2. MCP (no shell): ${mcpUrl} (OAuth): \`fork\`, then \`open_pull\` with a \`patch\`.`,
    `3. Web: ${origin}/ ; /{owner}/{name}/report needs no account.`,
    `Per repository: ${origin}/{owner}/{name}/AGENTS.md.`,
    "",
  ];
}

/** The text a repository without its own AGENTS.md is answered with. */
export function generatedAgentsMd(origin: string, owner: string, name: string, branch: string): string {
  const clone = `${origin}/${owner}/${name}.git`;
  return (
    [
      `# ${owner}/${name}: working on it`,
      "",
      `This repository has no AGENTS.md of its own; this one is generated by the forge at ${origin}. Read README.md and CLAUDE.md (when present) for the rest.`,
      "",
      "## Install",
      "",
      `- \`git clone ${clone} && cd ${name}\`, then \`bun install\` when there is a package.json and no node_modules.`,
      "",
      "## Run the tests",
      "",
      "- `bun test` (or the command forge.json names under `check` or `app.test`); `bun x tsc --noEmit` when there is a tsconfig.json; `bun scripts/gate.ts` when it exists.",
      "- Do not push while any of them is red.",
      "",
      "## Commits and pulls",
      "",
      "- Small commits with clear messages; one concern per pull. Work on a branch, never on the default branch: pushes to it are refused.",
      "- A pull's description says what changed, what was left out, and how to try it. A person reviews and merges.",
      "- Every behaviour you add has a test that would fail without it.",
      "",
      "## Contribute in five lines",
      "",
      `1. Fork it (MCP \`fork\`, or POST ${origin}/api/v1/repos/${owner}/${name}/forks).`,
      `2. Clone and push with a contribute token: \`git clone ${clone}\`, branch from ${branch}, \`git push origin <branch>\`; with no git, fetch ${origin}/${owner}/${name}/archive/${branch}.tar.gz.`,
      "3. Run the install and the tests above in your copy.",
      "4. Send it: the forge opens the pull on push, or MCP `open_pull` with a `patch` and `checks`.",
      `5. Found a problem and not a fix? ${origin}/${owner}/${name}/report needs no account. A sandbox needs one egress host: ${egressHost(origin)}.`,
      "",
    ].join("\n")
  );
}
