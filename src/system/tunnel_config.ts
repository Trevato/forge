/**
 * The host tunnel's ingress: the forge's three hostnames, then one rule per
 * verified app domain in the `app_domain` table, then a 404 catch-all. Plain data in
 * (hostnames), plain text out (cloudflared's yml). `scripts/tunnel-config.ts`
 * reads the table and writes `infra/forge-box/cloudflared-forge.yml`.
 */
import type { Database } from "bun:sqlite";

export const FORGE_ORIGIN = "http://127.0.0.1:3000";
export const FORGE_HOSTNAMES = [
  "forge.open-platform.sh",
  "*--forge.open-platform.sh",
  "*--forge-trevato-apps.open-platform.sh",
] as const;

/** Every app domain whose ownership is proven (`verified_at` set), sorted: an unproven host gets no public rule. */
export function appDomainHosts(db: Database): string[] {
  return db
    .query<{ host: string }, []>("SELECT host FROM app_domain WHERE verified_at IS NOT NULL ORDER BY host")
    .all()
    .map((r) => r.host);
}

const HOST = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

export function renderTunnelConfig(appHosts: readonly string[]): string {
  const hosts = [...new Set(appHosts)].sort();
  for (const h of hosts) if (!HOST.test(h)) throw new Error(`not a hostname: ${h}`);
  const rule = (h: string) => `  - hostname: "${h}"\n    service: ${FORGE_ORIGIN}`;
  return [
    "# Generated by `bun scripts/tunnel-config.ts`; do not edit by hand.",
    "# `tunnel` is the tunnel's own id, set on the box; the credentials file is a",
    "# secret kept in /etc/forge, never in the repository.",
    "tunnel: REPLACE-WITH-TUNNEL-ID",
    "credentials-file: /etc/forge/cloudflared.json",
    "ingress:",
    ...FORGE_HOSTNAMES.map(rule),
    "  # one rule per verified app domain (app_domain)",
    ...hosts.map(rule),
    "  - service: http_status:404",
    "",
  ].join("\n");
}
