/**
 * The tool table of docs/MCP.md, rendered from the live tool definitions:
 * name, the `action`/`kind` values it takes, the first sentence of its
 * description, and its bytes in `tools/list`. The doc holds it between two
 * markers; test/mcp-table.test.ts fails, naming the tool, when they differ.
 */
import { REPORT_TOOL, toolEntries } from "./mcp.ts";
import { TOOLS } from "./mcp/tools.ts";

export const TABLE_BEGIN = "<!-- mcp-tools:begin (generated by src/http/mcp_table.ts; edit the code, then run `bun scripts/mcp-table.ts`) -->";
export const TABLE_END = "<!-- mcp-tools:end -->";

export interface ToolRow {
  name: string;
  doors: string;
  purpose: string;
  bytes: number;
}

type Schema = { properties?: Record<string, { enum?: readonly string[] }> };

/** The values of the schema's `action` and `kind` enums, in order. */
function doorsOf(schema: unknown): string {
  const props = (schema as Schema).properties ?? {};
  return ["action", "kind"]
    .flatMap((k) => props[k]?.enum ?? [])
    .map((v) => `\`${v}\``)
    .join(", ");
}

/** `text` with what sits inside backticks or parentheses blanked, same length, to find a sentence end outside them. */
function outside(text: string): string {
  let depth = 0;
  let tick = false;
  let out = "";
  for (const ch of text) {
    if (ch === "`") {
      tick = !tick;
      out += " ";
    } else if (tick) out += " ";
    else if (ch === "(") {
      depth++;
      out += " ";
    } else if (ch === ")" && depth > 0) {
      depth--;
      out += " ";
    } else out += depth > 0 ? " " : ch;
  }
  return out;
}

/**
 * The first sentence, so a reworded tail never moves the table: it ends at
 * ". " or the end of the text, never inside backticks or parentheses. A bare
 * word ("Admin.") is no purpose; the next sentence is joined to it.
 */
export function firstSentence(text: string): string {
  const flat = text.replace(/\s+/g, " ").trim();
  const mask = outside(flat);
  const ends = [...mask.matchAll(/\.(?: |$)/g)].map((m) => m.index!);
  let cut = flat.length;
  for (const at of ends) {
    if (/\s/.test(flat.slice(0, at).trim())) {
      cut = at;
      break;
    }
  }
  return flat.slice(0, cut).replace(/\|/g, "\\|").trim();
}

export function toolRows(): ToolRow[] {
  const entries = toolEntries(TOOLS);
  const schemas = new Map<string, unknown>([...TOOLS.map((t) => [t.name, t.inputSchema] as const), [REPORT_TOOL.name, REPORT_TOOL.inputSchema]]);
  return entries.map((entry) => ({
    name: entry.name,
    doors: doorsOf(schemas.get(entry.name)),
    purpose: firstSentence(entry.description),
    bytes: Buffer.byteLength(JSON.stringify(entry)),
  }));
}

export function renderTable(rows: readonly ToolRow[] = toolRows()): string {
  return [
    "| Tool | Actions / kinds | Purpose | Bytes |",
    "| --- | --- | --- | ---: |",
    ...rows.map((r) => `| \`${r.name}\` | ${r.doors || "—"} | ${r.purpose} | ${r.bytes} |`),
  ].join("\n");
}

/** Where the table sits in `doc`; throws naming the marker that is missing, or the order that is wrong. */
function span(doc: string): [number, number] {
  const a = doc.indexOf(TABLE_BEGIN);
  const b = doc.indexOf(TABLE_END);
  if (a < 0) throw new Error(`docs/MCP.md has no begin marker: ${TABLE_BEGIN}`);
  if (b < 0) throw new Error(`docs/MCP.md has no end marker: ${TABLE_END}`);
  if (b < a) throw new Error("docs/MCP.md has the table end marker before the begin marker");
  return [a + TABLE_BEGIN.length, b];
}

/** The table between the markers in `doc`. */
export function tableIn(doc: string): string {
  const [a, b] = span(doc);
  return doc.slice(a, b).trim();
}

export function withTable(doc: string, table: string): string {
  const [a, b] = span(doc);
  return doc.slice(0, a) + "\n" + table + "\n" + doc.slice(b);
}
