/** The head a pattern or a path is marked by. */
export function headOf(path: string): string {
  const parts = path.split("/");
  return path.startsWith("/api/") ? parts.slice(0, 4).join("/") : `/${parts[1] ?? ""}`;
}

/** A pattern's mark, or undefined when it has none: a route that has not chosen. */
export function markOf(pattern: string): Mark | undefined {
  const own = ROUTES[pattern];
  if (own !== undefined) return own;
  const head = HEADS[headOf(pattern)];
  return head === "mixed" ? undefined : head;
}

let listed: Router<Mark> | undefined;
/** ROUTES as a matcher, literal segments before parameters so `/packs/new` is not read as `/packs/:name`. */
function listedRoutes(): Router<Mark> {
  if (listed !== undefined) return listed;
  const params = (p: string) => p.split("/").filter((s) => s.startsWith(":") || s.startsWith("*")).length;
  const matcher = new Router<Mark>();
  for (const pattern of Object.keys(ROUTES).sort((a, b) => params(a) - params(b)))
    matcher.add("*", pattern, ROUTES[pattern] as Mark);
  return (listed = matcher);
}

/** Whether a request path falls on a route marked `admin`; unlisted under a `mixed` head counts as `admin`. */
export function isAdminRoute(path: string): boolean {
  const own = listedRoutes().match("*", path);
  if (own !== undefined) return own.handler === "admin";
  const head = HEADS[headOf(path)];
  return head === "admin" || head === "mixed";
}
