/**
 * Which routes are an admin's, as data (#11818). Every route either router
 * registers is marked `admin` or `open` here, by its head — the first path
 * segment, or `/api/v1/<segment>` on the API — or, under a head marked
 * `mixed`, by its own pattern. A head holding both kinds is `mixed`, so each
 * of its routes chooses; a path under a `mixed` head that no listed route
 * matches is treated as `admin`, so a forgotten mark fails closed.
 *
 * `admin_gate.ts` refuses a signed-in account that may not administer every
 * path marked `admin`, before any handler runs; `open` routes keep their
 * handler's own rules. `test/route-marks.test.ts` walks both routers and
 * fails on a route marked neither, so a new route must choose here.
 */

