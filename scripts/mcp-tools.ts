/**
 * Writes the MCP tools' generated index, `src/http/mcp/tools/index.ts`, from
 * `src/http/mcp/tools/*.ts` (#5924): one sorted line per tool file, so a pull
 * that adds a tool adds one line and never edits another pull's.
 *
 * It writes no docs (#8304): the list of tools a reader sees is served live,
 * from each tool's `doc`, in /llms.txt's `## MCP tools` (`src/web/llms_tools.ts`).
 *
 *   bun scripts/mcp-tools.ts          write the index
 *   bun scripts/mcp-tools.ts --check  exit 1, naming the file, when it is stale
 *
 * `test/mcp-tools.test.ts` runs the check, so a pull that adds a tool file
 * without running this goes red with the command to run.
 *
 * @tree-scan: lists src/http/mcp/tools/ through a parameter's default.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const DIR = join(ROOT, "src/http/mcp/tools");
const INDEX = join(DIR, "index.ts");
const INDEX_NAME = "src/http/mcp/tools/index.ts";

/** The tool files, by name: every `<name>.ts` here but the index. */
export function toolFiles(dir = DIR): string[] {
  return readdirSync(dir)
    .filter((f) => /^[a-z][a-z0-9_]*\.ts$/.test(f) && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
}

export function indexText(names: readonly string[]): string {
  return [
    "// Generated by `bun scripts/mcp-tools.ts` from the files beside it; do not edit.",
    "// One line per tool, sorted: a new tool is a new file and one new line here.",
    ...names.map((n) => `export { tool as ${n} } from "./${n}.ts";`),
    "",
  ].join("\n");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const index = indexText(toolFiles());
  const stale = readFileSync(INDEX, "utf8") !== index;
  if (check && stale) {
    console.error(`stale: ${INDEX_NAME}; run \`bun scripts/mcp-tools.ts\``);
    process.exit(1);
  }
  if (stale && !check) writeFileSync(INDEX, index);
  if (!check) {
    console.log(`${stale ? "wrote" : "current"}: ${INDEX_NAME}, the only file this writes`);
    console.log("the tool list is served live from each tool's `doc` in /llms.txt; docs/MCP.md is not written");
  }
}
