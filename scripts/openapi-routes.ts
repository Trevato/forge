/**
 * Writes `src/contract/openapi/routes/index.ts` from the route files beside
 * it (#5936): one sorted line per file, so a pull that describes a route adds
 * one file and one line, and never edits another pull's.
 *
 *   bun scripts/openapi-routes.ts          write it
 *   bun scripts/openapi-routes.ts --check  exit 1 when it is stale
 *
 * `test/openapi-routes.test.ts` runs the same comparison, so a pull that adds
 * a route file without running this goes red with the command to run.
 *
 * @tree-scan: lists src/contract/openapi/routes/ through a parameter's default.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = join(import.meta.dir, "..", "src/contract/openapi/routes");
const INDEX = join(DIR, "index.ts");

/** The route files, by name: every `<operationId>.ts` here but the index. */
export function routeFiles(dir = DIR): string[] {
  return readdirSync(dir)
    .filter((f) => /^[a-z][A-Za-z0-9]*\.ts$/.test(f) && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
}

export function indexText(names: readonly string[]): string {
  return [
    "// Generated by `bun scripts/openapi-routes.ts` from the files beside it; do not edit.",
    "// One line per route, sorted: a new route is a new file and one new line here.",
    ...names.map((n) => `export { route as ${n} } from "./${n}.ts";`),
    "",
  ].join("\n");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const index = indexText(routeFiles());
  const current = readFileSync(INDEX, "utf8") === index;
  if (check && !current) {
    console.error("stale: src/contract/openapi/routes/index.ts; run `bun scripts/openapi-routes.ts`");
    process.exit(1);
  }
  if (!check && !current) writeFileSync(INDEX, index);
  if (!check) console.log(current ? "current" : "wrote src/contract/openapi/routes/index.ts");
}
